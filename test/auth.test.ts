import { describe, expect, it } from 'vitest';
import {
  AUTH_PASS,
  DEFAULT_LINK_KEY,
  FIXED_ADDR,
  authChallenge,
  authResponse,
  e1,
} from '../src/protocol/auth';
import { fromHex, toHex } from '../src/protocol/hex';

describe('E1 with the default Jieli key (docs/PROTOCOL.md §4 vectors, verified against vendor binary)', () => {
  const vectors: [string, string][] = [
    ['00112233445566778899aabbccddeeff', '26a69c072324c5e660c28ff912dcd857'],
    ['00000000000000000000000000000000', '9e43df377b3a46ce751634667e215de5'],
    ['0102030405060708090a0b0c0d0e0f10', '655d48686e418cf71f25fbc5cbeffa77'],
  ];
  it.each(vectors)('challenge %s -> %s', (challenge, expected) => {
    expect(toHex(e1(DEFAULT_LINK_KEY, fromHex(challenge), FIXED_ADDR), '')).toBe(expected);
  });
});

describe('E1 cross-check against jl_auth.py with random key/rand/addr', () => {
  // Generated by running jl_auth.e1 with random.seed(502).
  const vectors: [string, string, string, string][] = [
    ['ba56b456da14c2277ea36437a4777e20', '13232e58641019e3337a407e0856184d', '8b3180c5fd38', '81743c7bc77c3c64937d3e088f7eb709'],
    ['6d056a99bc335710cab665dffb2d379f', '7e2e6537a903bd247c0d0da3b3529b2f', 'b1fa04ffd5ff', '9b85e1b7205f23d84c3d24ad4bd6e82f'],
    ['c2d20a15afd92d09e1895b7e06e0e34b', 'b0f2b721ff9ed29a0f5e5603f52a714f', 'b26a41564766', '92d008cf58c01b4937ce35fb05317252'],
    ['3a558d7794677bd972fc4d36bc37c0f3', '6f8448eae9cf815de0283ec7807afef1', 'e90c39d2dc8e', 'f21b750efff046819d7a8bee1ab0186c'],
  ];
  it.each(vectors)('key %s', (key, rand, addr, expected) => {
    expect(toHex(e1(fromHex(key), fromHex(rand), fromHex(addr)), '')).toBe(expected);
  });
});

describe('auth messages', () => {
  it('response is 0x01 + E1 output, 17 bytes', () => {
    const r = authResponse(fromHex('00112233445566778899aabbccddeeff'));
    expect(toHex(r, '')).toBe('01' + '26a69c072324c5e660c28ff912dcd857');
  });
  it('challenge is 0x00 + 16 random bytes', () => {
    const c = authChallenge(fromHex('0102030405060708090a0b0c0d0e0f10'));
    expect(toHex(c, '')).toBe('000102030405060708090a0b0c0d0e0f10');
  });
  it('pass message is 02 "pass"', () => {
    expect(toHex(AUTH_PASS, '')).toBe('0270617373');
  });
  it('rejects wrong lengths', () => {
    expect(() => e1(DEFAULT_LINK_KEY, new Uint8Array(15), FIXED_ADDR)).toThrow(RangeError);
    expect(() => authChallenge(new Uint8Array(17))).toThrow(RangeError);
  });
});
